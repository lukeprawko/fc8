// Inicjalizacja metadanych kart (narodowości, ścieżki do zdjęć, rzadkości)
PLAYERS_DB.forEach(card => {
  card.nation = PLAYER_NATIONS[card.id] || '⚽';
  card.countryName = PLAYER_COUNTRIES[card.id] || 'Świat';
  card.image = 'assets/players/' + card.id + '.webp';
  if (card.ovr >= 90) card.rarity = 'ICON';
  else if (card.ovr >= 85) card.rarity = 'SPECIAL';
  else if (card.ovr >= 80) card.rarity = 'GOLD';
  else card.rarity = 'SILVER';
});

const cardsMap = new Map<string, PlayerCard>(PLAYERS_DB.map(c => [c.id, c]));

export function getCardById(id?: string | null): PlayerCard | undefined {
  if (!id) return undefined;
  return cardsMap.get(id);
}

export function getAllCards(): PlayerCard[] {
  return PLAYERS_DB;
}

export function getCardsByRole(role: PlayerRole): PlayerCard[] {
  return PLAYERS_DB.filter(c => c.role === role);
}

export function getStarterCards(): PlayerCard[] {
  return STARTER_CARD_IDS.map(id => getCardById(id)!).filter(Boolean);
}
