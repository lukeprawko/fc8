  function acceptGuess(player, point) {
    if (!isHost || match?.phase !== "playing" || match.submitted[player] ||
        hostNow() < match.startAt || hostNow() >= match.deadline || !validPoint(point)) return;
    match.guesses[player] = { lat: point.lat, lng: point.lng };
    match.drafts[player] = match.guesses[player]; match.submitted[player] = true;
    send({ type: "locked", round: match.round, locked: match.submitted }); updateGuessUI();
    if (match.submitted.every(Boolean)) finishRound();
  }
  function finishRound() {
    if (!isHost || match?.phase !== "playing") return;
    // At the deadline the last marker received by the host is automatically submitted.
    const guesses = match.guesses.map((g, i) => match.submitted[i] ? g : match.drafts[i]);
    send({ type: "reveal", round: match.round, guesses }); reveal(guesses);
  }
