        if (!active()) return;
        clearTimeout(imageTimer); $("retry-image").hidden = true;
        match.ready[myIndex()] = true;
        text("loading-message", solo ? "Gotowe. Przygotuj się!" : "Panorama gotowa. Czekamy na drugiego gracza…");
